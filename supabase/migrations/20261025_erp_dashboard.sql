-- 11. Helper Function: Audit Log Helper
-- ---------------------------------------------------------------------------
create or replace function public.log_audit_event(
  p_action text,
  p_entity_type text,
  p_entity_id text,
  p_details text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.audit_logs (user_id, user_email, action, entity_type, entity_id, details)
  values (
    auth.uid(),
    coalesce((select email from auth.users where id = auth.uid()), 'system'),
    p_action,
    p_entity_type,
    p_entity_id,
    p_details
  );
end;
$$;
