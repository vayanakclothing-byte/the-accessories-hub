-- Drop any existing policies on these tables to avoid duplicates
do $$
declare
  policy_row record;
begin
  for policy_row in
    select schemaname, tablename, policyname
    from pg_policies
    where schemaname = 'public'
      and tablename in ('suppliers', 'purchase_orders', 'purchase_order_items', 'expenses',
                        'shipments', 'returns_refunds', 'coupons', 'audit_logs',
                        'notifications', 'reviews')
  loop
    execute format('drop policy %I on %I.%I',
                   policy_row.policyname, policy_row.schemaname, policy_row.tablename);
  end loop;
end;
$$;

